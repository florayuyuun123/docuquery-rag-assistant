/**
 * Shared TypeScript types for the DocuQuery RAG Assistant.
 * Used by both backend Lambda functions and the frontend React application.
 * This module has no runtime dependencies.
 */

// ---------------------------------------------------------------------------
// Document status state machine
// Transitions are monotonic: once "ready" or "failed", no further transitions.
//   uploaded → processing → ready
//                 ↓
//               failed  (also: uploaded → failed on post-upload step failure)
// ---------------------------------------------------------------------------

/** The lifecycle status of a document as it moves through the ingestion pipeline. */
export type DocumentStatus = "uploaded" | "processing" | "ready" | "failed";

// ---------------------------------------------------------------------------
// DynamoDB record shapes
// ---------------------------------------------------------------------------

/**
 * A document record stored in the DynamoDB single-table design.
 *
 * PK = USER#{userId}
 * SK = DOC#{documentId}
 */
export interface DocumentRecord {
  /** Partition key: USER#{userId} */
  PK: string;
  /** Sort key: DOC#{documentId} */
  SK: string;
  /** Cognito sub (UUID) of the document owner. */
  userId: string;
  /** UUID identifying the document within the system. */
  documentId: string;
  /** Original file name provided by the user at upload time. */
  documentName: string;
  /** S3 object key: USER#{userId}/DOC#{documentId}/{originalFileName} */
  s3Key: string;
  /** File size in bytes. Maximum 20,971,520 (20 MB). */
  fileSize: number;
  /** MIME content type: "application/pdf", "application/vnd.openxmlformats-officedocument.wordprocessingml.document", or "text/plain". */
  contentType: string;
  /** Current status of the document in the ingestion pipeline. */
  status: DocumentStatus;
  /** ISO-8601 UTC timestamp when the record was first created. */
  createdAt: string;
  /** ISO-8601 UTC timestamp when the record was last modified. */
  updatedAt: string;
}

/**
 * A chat session record stored in DynamoDB.
 *
 * PK = USER#{userId}
 * SK = CHAT#{sessionId}#{ISO-timestamp}
 */
export interface ChatRecord {
  /** Partition key: USER#{userId} */
  PK: string;
  /** Sort key: CHAT#{sessionId}#{ISO-timestamp} */
  SK: string;
  /** Cognito sub (UUID) of the user who initiated the chat. */
  userId: string;
  /** UUID identifying the chat session. */
  sessionId: string;
  /** The natural-language question submitted by the user. */
  question: string;
  /** The answer generated by the Claude model (or a fallback message). */
  answer: string;
  /** The citations that back the answer. Empty array for fallback responses. */
  citations: Citation[];
  /**
   * True when the answer is a fallback (no relevant chunks found or no ready
   * documents available). False for a genuine RAG-grounded answer.
   */
  isFallback: boolean;
  /** ISO-8601 UTC timestamp when the chat record was created. */
  createdAt: string;
}

// ---------------------------------------------------------------------------
// Knowledge Base / RAG types
// ---------------------------------------------------------------------------

/**
 * Metadata attached to each text chunk indexed in the Bedrock Knowledge Base.
 * This metadata is persisted alongside the chunk embedding and is used to
 * filter retrieval by userId (per-user isolation) and to assemble citations.
 */
export interface ChunkMetadata {
  /** Cognito sub (UUID) of the document owner — used as the retrieval filter. */
  userId: string;
  /** UUID of the parent document. */
  documentId: string;
  /** Original file name of the parent document. */
  documentName: string;
  /**
   * 1-based page number within the source document.
   * null for TXT files, which carry no page metadata.
   */
  pageNumber: number | null;
  /** 0-based index of this chunk within the document. */
  chunkIndex: number;
  /** The format of the source document. */
  sourceFormat: "pdf" | "docx" | "txt";
}

/**
 * A citation attached to a chat answer, identifying the source chunk that
 * supports the answer text.
 */
export interface Citation {
  /** UUID of the source document. */
  documentId: string;
  /** Original file name of the source document. */
  documentName: string;
  /**
   * 1-based page number in the source document.
   * null for TXT files that do not carry page metadata.
   */
  pageNumber: number | null;
  /** The verbatim passage text of the chunk as stored in the Knowledge Base. */
  chunkText: string;
  /** Semantic similarity score in the range [0, 1] from the KB retrieve call. */
  relevanceScore: number;
}

// ---------------------------------------------------------------------------
// API envelope types
// ---------------------------------------------------------------------------

/**
 * Generic success response wrapper returned by all API endpoints.
 *
 * @template T - The shape of the response payload.
 */
export interface ApiResponse<T> {
  /** The response payload. */
  data: T;
  /** A UUID v4 correlation ID for tracing the request across services. */
  correlationId: string;
}

/**
 * Error response returned by the API when a request fails.
 * Returned for 4xx and 5xx HTTP responses.
 */
export interface ErrorResponse {
  /** A short error code or category (e.g. "VALIDATION_ERROR", "FORBIDDEN"). */
  error: string;
  /** A human-readable description of what went wrong. */
  message: string;
  /** A UUID v4 correlation ID for tracing the request across services. */
  correlationId: string;
  /** The HTTP status code (e.g. 400, 403, 404, 500, 502, 504). */
  statusCode: number;
}
